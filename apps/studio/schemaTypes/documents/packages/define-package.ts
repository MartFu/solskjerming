/**
 * Parameters passed to initial value templates when creating a document.
 * These are provided by the Studio UI (page tree, create modal) and
 * used to wire up site context and parent relationships automatically.
 */
export interface TemplateParams {
  siteId: string;
  parentId?: string;
  title?: string;
}

/**
 * A Sanity initial value template generated by `definePackage`.
 * Spread these into your Sanity config's `schema.templates` array.
 */
export interface InitialValueTemplate {
  id: string;
  title: string;
  schemaType: string;
  icon?: ComponentType | ReactNode;
  parameters: Array<{ name: string; type: string }>;
  value: (params: TemplateParams) => Record<string, unknown>;
}

/**
 * Presentation overrides for a global document type within a package's
 * structure tool context. The global's schema is defined once centrally;
 * these options control how it appears in the Studio sidebar when this
 * package is enabled.
 *
 * @typeParam T - The global type name, used to constrain `defaultOrdering`
 *               fields to only those declared in the global's `sortFields`.
 */
export interface GlobalPresentationConfig<T extends GlobalType = GlobalType> {
  /** Override the display title in the structure tool */
  structureTitle?: string;

  /** Override the icon in the structure tool */
  icon?: ComponentType | ReactNode;

  /** Override default ordering — field names are constrained to this global's sortFields */
  defaultOrdering?: { field: GlobalFieldNames<T>; direction: "asc" | "desc" }[];
}

/**
 * Configuration for a single document role within a package.
 *
 * A "role" is a named slot in the package's document tree. Role keys are
 * freeform and semantic — use names that describe the document's purpose
 * (e.g. "hub", "featureGroup", "article", "topic"). Structural meaning
 * (entry points, parent-child relationships) is derived from
 * `allowPageAsParent` and `allowedParentRoles`, not from the key name.
 *
 * @typeParam K - Union of role keys defined in the parent `PackageConfig`.
 *               Used to constrain `allowedParentRoles` for type-safe
 *               autocomplete.
 */
export interface DocumentRoleConfig<K extends string = string> {
  /** Sanity schema type name, e.g. "saas.hub" or "kb.article" */
  name: string;

  /** Human-readable title shown in Studio, e.g. "Product Overview" */
  title: string;

  /** Icon shown in Studio lists and structure */
  icon: ComponentType | ReactNode;

  /** Description shown in package selection UI */
  description?: string;

  /**
   * Whether this document can be placed under a "page" document in the
   * site tree. This is the structural definition of an **entry point**.
   *
   * Typically true for root-level documents that need to appear in the
   * site's page tree. Documents without this flag (and without
   * `allowedParentRoles`) cannot be placed anywhere in the tree.
   *
   * @default false
   */
  allowPageAsParent?: boolean;

  /**
   * Which other roles within THIS package can be a parent of this document.
   * Uses role keys — resolved to Sanity type names automatically.
   *
   * A role can reference itself for recursive types (e.g. a topic that
   * can nest under another topic).
   *
   * @example
   * allowedParentRoles: ["hub"]            // can only live under the hub
   * allowedParentRoles: ["root", "topic"]  // under root, or nested under itself
   */
  allowedParentRoles?: NoInfer<K>[];

  /**
   * Pagebuilder type name. When provided, the document gets a pagebuilder
   * field. Typically used for entry-point documents that need flexible
   * page layouts.
   */
  pagebuilderType?: PageBuilderType;

  /** Type-specific fields appended after the common fields. */
  extraFields?: FieldDefinition[];

  /** Override the default preview config. */
  preview?: PreviewConfig;

  /** Override which group tab opens by default. */
  defaultGroup?: GroupValue;

  /** Whether the Studio UI allows setting/changing this document's parent. */
  setParentAllowed?: boolean;

  /**
   * Additional initial values for new documents of this type.
   *
   * The core fields (`site`, `parent`, `title`) are always set
   * automatically from the creation context. Values provided here
   * are merged on top — use this for type-specific defaults like
   * a default date, status, or category.
   *
   * Can be a static object or a function that receives the template
   * params and returns an object.
   *
   * @example
   * // Static extra values
   * initialValues: { status: "draft" }
   *
   * // Dynamic extra values
   * initialValues: (params) => ({
   *   publishedAt: new Date().toISOString().split("T")[0],
   * })
   */
  initialValues?:
    | Record<string, unknown>
    | ((params: TemplateParams) => Record<string, unknown>);
}

/**
 * Top-level configuration passed to `definePackage`.
 *
 * A package groups related document types into a logical unit that can be
 * enabled or disabled per site. The `documents` map uses freeform role
 * keys — structural meaning is derived from each role's config, not from
 * the key name.
 *
 * @typeParam K - Union of role keys, inferred from the `documents` object.
 */
export interface PackageConfig<K extends string = string> {
  /**
   * Unique key identifying this package, e.g. "articles", "commerce".
   * Used in the site's `enabledPackages` field and in lookup maps.
   */
  key: PackageKey;

  /** Human-readable package name, e.g. "Artikler", "Netthandel" */
  title: string;

  /**
   * Global document types this package uses when enabled.
   *
   * Pass `true` to include the global with default presentation, or
   * pass a `GlobalPresentationConfig` to override how it appears in
   * the structure tool.
   *
   * The global's schema is defined centrally — this only controls
   * whether it appears in the Studio sidebar and how it's presented
   * when this package is enabled on a site.
   *
   * @example
   * globals: {
   *   product: true,
   *   author: {
   *     structureTitle: "Produktforfattere",
   *     defaultOrdering: [{ field: "name", direction: "asc" }],
   *   },
   * }
   */
  globals?: { [G in GlobalType]?: boolean | GlobalPresentationConfig<G> };

  /**
   * Document roles in this package, keyed by semantic role name.
   *
   * Each key becomes a role identifier used in `allowedParentRoles`.
   * Structure (entry points, parent-child relationships) is derived
   * from each role's `allowPageAsParent` and `allowedParentRoles` config.
   *
   * @example
   * documents: {
   *   hub:          { name: "saas.hub", allowPageAsParent: true, ... },
   *   featureGroup: { name: "saas.featureGroup", allowedParentRoles: ["hub"], ... },
   *   feature:      { name: "saas.feature", allowedParentRoles: ["featureGroup"], ... },
   * }
   */
  documents: { [R in K]: DocumentRoleConfig<K> };
}

