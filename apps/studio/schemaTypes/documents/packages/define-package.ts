/**
 * Resolved metadata for a single document role.
 *
 * This is what the Studio structure builder and document actions consume.
 * Parent relationships are fully resolved to Sanity type names.
 */
export interface DocumentRoleMeta {
  /** Sanity schema type name */
  type: string;

  /** Human-readable title */
  title: string;

  /** Studio icon */
  icon: ComponentType | ReactNode;

  /** Optional description for UI */
  description?: string;

  /** Generated template ID for creation flows (e.g. "pkg-commerce-catalog") */
  templateId: string;

  /** Whether the Studio UI allows changing this document's parent */
  setParentAllowed: boolean;

  /** The role key from the package config */
  role: string;

  /** Resolved Sanity type names that can be parents of this document */
  resolvedParentTypes: string[];

  /** Whether this document can live under a Page in the site tree */
  isEntryPoint: boolean;
}

/**
 * Resolved configuration for a global document type within a package.
 * Merges the package's presentation overrides with computed defaults.
 */
export interface ResolvedGlobalConfig {
  /** The global type name (e.g. "product", "author") */
  type: string;

  /** Display title for the structure tool */
  structureTitle: string;

  /** Unique ID for the structure tool list item (e.g. "global-commerce-product") */
  structureId: string;

  /** Icon for the structure tool, falls back to the global's own icon */
  icon?: ComponentType | ReactNode;

  /** GROQ filter for the document list, scoped to this package's documents */
  filter: string;

  /** Default ordering for the document list */
  defaultOrdering: { field: string; direction: "asc" | "desc" }[];
}

/**
 * The fully resolved output of `definePackage`.
 *
 * Contains Sanity schema definitions (ready to spread into your schema
 * array), initial value templates, and metadata the Studio uses for
 * structure building, document creation, and package management.
 *
 * @typeParam K - Union of role keys from the original config.
 */
export interface PackageResult<K extends string = string> {
  /** Unique package key */
  key: PackageKey;

  /** Human-readable title */
  title: string;

  /**
   * Sanity `defineType` results — spread these into your schema.
   * One entry per document role in the package.
   */
  schemas: ReturnType<typeof defineType>[];

  /**
   * Initial value templates for document creation.
   * Spread these into your Sanity config's `schema.templates` array.
   * One template per document role, with site/parent/title wiring built in.
   */
  templates: InitialValueTemplate[];

  /**
   * Resolved metadata for each document role, keyed by role name.
   * Use this for structure builder, document actions, and UI.
   */
  documents: Record<K, DocumentRoleMeta>;

  /**
   * Resolved globals config, keyed by global type name.
   * Used by the structure builder to create document lists.
   */
  globals: Record<string, ResolvedGlobalConfig>;
}

