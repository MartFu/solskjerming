/**
 * Resolves role keys (e.g. "hub", "topic") into Sanity type names
 * (e.g. "saas.hub", "kb.topic"). Validates that referenced roles exist.
 */
function _resolveParentTypes(
  roleKey: string,
  roleConfig: DocumentRoleConfig<string>,
  allRoles: Record<string, DocumentRoleConfig<string>>,
): string[] {
  const parents = new Set<string>();

  if (roleConfig.allowPageAsParent) {
    parents.add("page");
  }

  for (const ref of roleConfig.allowedParentRoles ?? []) {
    if (allRoles[ref]) {
      parents.add(allRoles[ref].name);
    } else {
      throw new Error(
        `Role "${roleKey}" references parent role "${ref}" which does not exist in this package.`,
      );
    }
  }

  return Array.from(parents);
}

/**
 * Resolves the globals config from the package config into a map of
 * `ResolvedGlobalConfig` entries. Pulls default title, icon, and ordering
 * from the global's own definition (via `GLOBAL_REGISTRY`), then applies
 * any package-level overrides.
 *
 * The GROQ filter is scoped to only show globals that are referenced by
 * documents this package owns.
 */
function _resolveGlobals(
  packageKey: string,
  globalsConfig: PackageConfig["globals"],
  packageDocumentTypes: string[],
): Record<string, ResolvedGlobalConfig> {
  const resolved: Record<string, ResolvedGlobalConfig> = {};

  if (!globalsConfig) return resolved;

  for (const [globalType, config] of Object.entries(globalsConfig)) {
    if (!config) continue;

    const globalDef = GLOBAL_REGISTRY[globalType as GlobalType];
    const overrides = typeof config === "boolean" ? {} : config;

    // Runtime validation: ensure ordering fields exist in sortFields
    if (overrides.defaultOrdering && globalDef) {
      const validFields = new Set(globalDef.sortFields);
      for (const ordering of overrides.defaultOrdering) {
        if (!validFields.has(ordering.field)) {
          throw new Error(
            `Global "${globalType}" has no sortable field "${ordering.field}". ` +
              `Available sort fields: ${globalDef.sortFields.join(", ")}`,
          );
        }
      }
    }

    const typeList = JSON.stringify(packageDocumentTypes);

    resolved[globalType] = {
      type: globalType,
      structureTitle:
        overrides.structureTitle ?? globalDef?.schema.title ?? globalType,
      structureId: `global-${packageKey}-${globalType}`,
      icon: overrides.icon ?? globalDef?.schema.icon,
      filter: `_type == "${globalType}" && count(*[_type in ${typeList} && references(^._id)]) > 0`,
      defaultOrdering: overrides.defaultOrdering ?? [
        {
          field: globalDef?.sortFields[0] ?? "title",
          direction: "asc" as const,
        },
      ],
    };
  }

  return resolved;
}

/**
 * Builds an initial value template for a document role.
 * Handles site/parent/title wiring automatically, then merges any
 * consumer-provided initial values on top.
 */
function _buildTemplate(
  packageKey: string,
  roleKey: string,
  roleConfig: DocumentRoleConfig<string>,
): InitialValueTemplate {
  const templateId = `pkg-${packageKey}-${roleKey}-template`;

  return {
    id: templateId,
    title: roleConfig.title,
    schemaType: roleConfig.name,
    icon: roleConfig.icon,
    parameters: [...TEMPLATE_PARAMETERS],
    value: (params: TemplateParams) => {

      // Core fields — always set from creation context
      const base: Record<string, unknown> = {};

      if (params.title) {
        base.title = params.title;
      }

      if (params.siteId) {
        base.site = { _type: "reference", _ref: params.siteId };
      }

      if (params.parentId) {
        base.parent = { _type: "reference", _ref: params.parentId };
      }

      // Consumer-provided extra values
      const extra =
        typeof roleConfig.initialValues === "function"
          ? roleConfig.initialValues(params)
          : (roleConfig.initialValues ?? {});

      // Extra values merge on top, but core fields always win
      return { ...extra, ...base };
    },
  };
}

/**
 * Assembles the full field list for a document role.
 */
function _buildFields(
  role: DocumentRoleConfig<string>,
  resolvedParentTypes: string[],
): FieldDefinition[] {
  const { pagebuilderType, extraFields = [] } = role;

  return [
    ...createIdentityFields(),
    ...createParentField(resolvedParentTypes),
    ...createSortOrderField(),
    ...createPageSEOFields(),
    ...(pagebuilderType ? createPagebuilderField(pagebuilderType) : []),
    ...extraFields,
  ];
}

