/**
 * Create lookup maps and constants from an array of PackageResults.
 *
 * Call this once after defining all packages. The registry validates
 * that document type names are unique across packages, derives
 * entry points from config, and provides lookup helpers for the
 * Studio structure builder and document actions.
 *
 * @example
 * ```ts
 * const articles = definePackage({ ... });
 * const commerce = definePackage({ ... });
 *
 * export const registry = createPackageRegistry([articles, commerce]);
 *
 * registry.allSchemas              // every schema from every package
 * registry.allTemplates            // every template, ready for schema.templates
 * registry.allEntryTypes           // ["page", "catalogRoot", ...]
 * registry.lookup("productPage")   // { package, meta } or undefined
 * registry.globalsForPackages(["commerce"]) // resolved globals for enabled pkgs
 * ```
 */
export function createPackageRegistry(packages: PackageResult<string>[]) {
  const allSchemas = packages.flatMap((pkg) => pkg.schemas);
  const allTemplates = packages.flatMap((pkg) => pkg.templates);

  const byType = new Map<
    string,
    { package: PackageResult<string>; meta: DocumentRoleMeta }
  >();
  const byKey = new Map<string, PackageResult<string>>();
  const entryPointTypes = new Set<string>(["page"]);

  for (const pkg of packages) {
    if (byKey.has(pkg.key)) {
      throw new Error(
        `Duplicate package key "${pkg.key}". Package keys must be unique.`,
      );
    }
    byKey.set(pkg.key, pkg);

    for (const meta of Object.values<DocumentRoleMeta>(pkg.documents)) {
      if (byType.has(meta.type)) {
        const existing = byType.get(meta.type)!;
        throw new Error(
          `Duplicate document type "${meta.type}" found in packages "${existing.package.key}" and "${pkg.key}". Document type names must be unique.`,
        );
      }

      byType.set(meta.type, { package: pkg, meta });

      if (meta.isEntryPoint) {
        entryPointTypes.add(meta.type);
      }
    }
  }

  return {
    /** All registered packages */
    packages,

    /** Every schema from every package, ready to spread into Sanity config */
    allSchemas,

    /**
     * Every initial value template from every package.
     * Use in your Sanity config: `schema.templates: (prev) => [...prev, ...registry.allTemplates]`
     */
    allTemplates,

    /** All document types that can appear at the top level of the site tree */
    allEntryTypes: Array.from(entryPointTypes),

    /** For UI dropdowns (site's enabledPackages field, etc.) */
    packageOptions: packages.map((pkg) => ({
      title: pkg.title,
      value: pkg.key,
    })),

    /** Find the package and role metadata for any Sanity type name */
    lookup: (typeName: string) => byType.get(typeName),

    /** Find a package by its key */
    getPackage: (key: string) => byKey.get(key),

    /**
     * Collect resolved globals for a set of enabled package keys.
     * Each package gets its own entries — if multiple packages claim
     * the same global type, each appears with its own presentation
     * config and package-scoped filter.
     */
    globalsForPackages: (
      enabledKeys: string[],
    ): Array<ResolvedGlobalConfig & { packageKey: string }> => {
      const result: Array<ResolvedGlobalConfig & { packageKey: string }> = [];

      for (const key of enabledKeys) {
        const pkg = byKey.get(key);
        if (!pkg) continue;

        for (const config of Object.values(pkg.globals)) {
          result.push({ ...config, packageKey: key });
        }
      }

      return result;
    },
  };
}
