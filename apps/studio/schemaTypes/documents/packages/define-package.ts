/**
 * Define a complete package: schemas + metadata + templates in one declaration.
 *
 * This is the primary entry point for extending the system with new
 * content types. Each call produces:
 *
 * 1. Sanity schema definitions for every document role.
 * 2. Initial value templates with automatic site/parent/title wiring.
 * 3. Metadata for structure building, document creation, and package management.
 *
 * Role keys are freeform — use descriptive names like `"hub"`,
 * `"featureGroup"`, `"article"`. Structure is derived from each
 * role's `allowPageAsParent` and `allowedParentRoles` config.
 * TypeScript provides full autocomplete on `allowedParentRoles`
 * based on the keys you define.
 *
 * @example
 * ```ts
 * const commerce = definePackage({
 *   key: "commerce",
 *   title: "Netthandel",
 *   globals: {
 *     product: {
 *       structureTitle: "Produkter",
 *       defaultOrdering: [{ field: "title", direction: "asc" }],
 *     },
 *   },
 *   documents: {
 *     catalog: {
 *       name: "catalogRoot",
 *       title: "Katalog",
 *       icon: ShoppingCart,
 *       allowPageAsParent: true,
 *       pagebuilderType: "catalogRootPageBuilder",
 *     },
 *     productPage: {
 *       name: "productPage",
 *       title: "Produktside",
 *       icon: PackageIcon,
 *       allowedParentRoles: ["catalog"],
 *       initialValues: {
 *         publishedAt: new Date().toISOString().split("T")[0],
 *       },
 *     },
 *   },
 * });
 *
 * // Register in Sanity config:
 * const schemas = [...commerce.schemas];
 * const templates = (prev) => [...prev, ...commerce.templates];
 *
 * // Access metadata:
 * commerce.documents.catalog.templateId     // "pkg-commerce-catalog"
 * commerce.documents.catalog.isEntryPoint   // true
 * commerce.documents.productPage.resolvedParentTypes // ["catalogRoot"]
 * ```
 */
export function definePackage<K extends string>(
  config: PackageConfig<K>,
): PackageResult<K> {
  const { key, title, documents } = config;

  const schemas: ReturnType<typeof defineType>[] = [];
  const templates: InitialValueTemplate[] = [];
  const documentsMeta = {} as Record<K, DocumentRoleMeta>;

  for (const [roleKey, roleConfig] of Object.entries<DocumentRoleConfig<K>>(
    documents,
  )) {
    const resolvedParentTypes = _resolveParentTypes(
      roleKey,
      roleConfig,
      documents,
    );

    const templateId = `pkg-${key}-${roleKey}-template`;

    // Build schema
    const schema = defineType({
      name: roleConfig.name,
      title: roleConfig.title,
      type: "document",
      icon: roleConfig.icon,
      groups: GROUPS(roleConfig.defaultGroup ?? GROUP.IDENTITY),
      fields: _buildFields(roleConfig, resolvedParentTypes),
      preview: roleConfig.preview ?? defaultPreview,
    });

    schemas.push(schema);

    // Build template
    templates.push(_buildTemplate(key, roleKey, roleConfig));

    // Build metadata
    documentsMeta[roleKey as K] = {
      type: roleConfig.name,
      title: roleConfig.title,
      icon: roleConfig.icon,
      description: roleConfig.description,
      templateId,
      setParentAllowed: roleConfig.setParentAllowed ?? false,
      role: roleKey,
      resolvedParentTypes,
      isEntryPoint: !!roleConfig.allowPageAsParent,
    };
  }

  const packageDocumentTypes = Object.values<DocumentRoleConfig<K>>(
    documents,
  ).map((r) => r.name);
  const globals = _resolveGlobals(key, config.globals, packageDocumentTypes);

  return { key, title, schemas, templates, documents: documentsMeta, globals };
}

